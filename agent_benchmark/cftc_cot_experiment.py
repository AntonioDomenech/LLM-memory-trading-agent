def _committed_artifact_snapshot(
    repo_root: Path,
    run_dir: Path,
    *,
    head_commit: str,
) -> dict[str, bytes]:
    """Read the sealed development directory once from an immutable Git tree.

    Confirmation must not authenticate a worktree file and then reopen a
    potentially different byte sequence for replay.  The caller captures HEAD
    before entering this function; every artifact below is enumerated and read
    from that exact commit rather than from mutable filesystem paths.
    """

    try:
        relative_dir = run_dir.resolve().relative_to(repo_root.resolve())
    except ValueError as exc:
        raise CFTCExperimentError(
            "Development artifacts must be committed inside the source repository"
        ) from exc

    relative_dir_text = relative_dir.as_posix().rstrip("/")
    if not relative_dir_text or relative_dir_text == ".":
        raise CFTCExperimentError("Development artifacts require a dedicated run directory")
    tree = subprocess.run(
        [
            "git",
            "ls-tree",
            "-r",
            "--name-only",
            "-z",
            head_commit,
            "--",
            relative_dir_text,
        ],
        cwd=repo_root,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if tree.returncode != 0:
        raise CFTCExperimentError(
            "Could not enumerate development artifacts from the captured Git commit"
        )
    try:
        relative_paths = [
            value.decode("utf-8", errors="strict")
            for value in bytes(tree.stdout).split(b"\0")
            if value
        ]
    except UnicodeDecodeError as exc:
        raise CFTCExperimentError("Committed development artifact path is not UTF-8") from exc
    if not relative_paths:
        raise CFTCExperimentError(
            "Development artifacts are not tracked at the captured Git commit"
        )

    snapshot: dict[str, bytes] = {}
    for relative_path_text in relative_paths:
        relative_path = Path(relative_path_text)
        if relative_path.parent.as_posix() != relative_dir_text:
            raise CFTCExperimentError(
                "Development artifact directory must not contain nested files"
            )
        name = relative_path.name
        if name in snapshot:
            raise CFTCExperimentError(f"Duplicate committed development artifact name: {name}")
        blob = subprocess.run(
            ["git", "cat-file", "blob", f"{head_commit}:{relative_path_text}"],
            cwd=repo_root,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
        )
        if blob.returncode != 0:
            raise CFTCExperimentError(
                f"Could not read committed development artifact: {name}"
            )
        snapshot[name] = bytes(blob.stdout)
    return snapshot


def _snapshot_json(snapshot: Mapping[str, bytes], name: str) -> Any:
    payload = snapshot.get(name)
    if payload is None:
        raise CFTCExperimentError(f"Development artifact is missing: {name}")
    try:
        return json.loads(payload.decode("utf-8", errors="strict"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise CFTCExperimentError(f"Development artifact is not valid JSON: {name}") from exc


def _load_development_seal(
    path: Path,
    *,
    repo_root: Path,
    head_commit: str | None = None,
) -> tuple[dict[str, Any], CleanCOTRecords, dict[str, Any], pd.DataFrame]:
    report_path = path / "report.json" if path.is_dir() else path
    run_dir = report_path.parent
    if report_path.name != "report.json":
        raise CFTCExperimentError("Development seal path must name report.json or its directory")
    captured_head = str(head_commit or _git_state(repo_root).get("commit") or "")
    if not captured_head:
        raise CFTCExperimentError("Could not capture Git HEAD for development replay")
    snapshot = _committed_artifact_snapshot(
        repo_root,
        run_dir,
        head_commit=captured_head,
    )
    expected_checksums = _snapshot_json(snapshot, "checksums.json")
    if not isinstance(expected_checksums, dict):
        raise CFTCExperimentError("Development checksum manifest must be a JSON object")
    actual_files = set(snapshot) - {"checksums.json"}
    if set(expected_checksums) != actual_files:
        raise CFTCExperimentError("Development checksum manifest does not cover the exact artifact files")
    for name, expected_hash in expected_checksums.items():
        artifact_bytes = snapshot.get(name)
        if artifact_bytes is None or _sha256_hex_bytes(artifact_bytes) != expected_hash:
            raise CFTCExperimentError(f"Development artifact checksum mismatch: {name}")
    report = _snapshot_json(snapshot, "report.json")
    if not isinstance(report, dict):
        raise CFTCExperimentError("Development report must be a JSON object")
    if report.get("stage") != "development" or report.get("development_pass") is not True:
        raise CFTCExperimentError("Confirmation requires a passing development report")
    manifest = report.get("selection_manifest") or {}
    embedded_hash = manifest.get("manifest_sha256")
    payload = {key: value for key, value in manifest.items() if key != "manifest_sha256"}
    if not embedded_hash or embedded_hash != _sha256_json(payload):
        raise CFTCExperimentError("Development selection manifest hash is invalid")
    if _snapshot_json(snapshot, "selection_manifest.json") != manifest:
        raise CFTCExperimentError("Development manifest file differs from the sealed report")
    artifact_hashes = report.get("artifact_sha256") or {}
    for name, expected_hash in artifact_hashes.items():
        artifact_bytes = snapshot.get(name)
        if artifact_bytes is None or _sha256_hex_bytes(artifact_bytes) != expected_hash:
            raise CFTCExperimentError(f"Development embedded artifact hash mismatch: {name}")
    results = report.get("candidate_results") or []
    if manifest.get("evaluation_results_sha256") != _sha256_json(results):
        raise CFTCExperimentError("Development candidate results are not bound by the manifest")
    selected = select_development_variant(results)
    if not selected:
        raise CFTCExperimentError("Development candidate results no longer contain a passing winner")
    if selected != report.get("selected_variant_id") or selected != manifest.get("selected_variant_id"):
        raise CFTCExperimentError("Development winner differs across results, report, and manifest")
    get_cftc_cot_variant(selected)
    if report.get("integrity_errors") or report.get("development_pass") is not True:
        raise CFTCExperimentError("Development report is not an integrity-clean passing seal")
    if manifest.get("stage") != "development" or manifest.get("physical_data_end") != DEVELOPMENT_END:
        raise CFTCExperimentError("Development manifest has the wrong evidence stage or boundary")
    if manifest.get("parent_development_manifest_sha256") is not None:
        raise CFTCExperimentError("Development manifest unexpectedly has a parent seal")
    if manifest.get("candidate_family") != [item.to_dict() for item in CFTC_COT_VARIANTS]:
        raise CFTCExperimentError("Development manifest candidate family is not the frozen four")
    if manifest.get("runtime_identity") != runtime_identity():
        raise CFTCExperimentError("Numerical runtime differs from frozen development")
    price_bytes = snapshot.get("development_prices_through_2018.csv")
    cftc_bytes = snapshot.get("development_cftc_raw_through_2018.csv")
    cftc_count_bytes = snapshot.get(
        "development_cftc_official_count_proof_through_2018.csv"
    )
    if price_bytes is None or _sha256_bytes(price_bytes) != manifest.get("price_sha256"):
        raise CFTCExperimentError("Development price bytes differ from the manifest")
    if cftc_bytes is None or _sha256_bytes(cftc_bytes) != manifest.get("cftc_raw_sha256"):
        raise CFTCExperimentError("Development CFTC bytes differ from the manifest")
    if cftc_count_bytes is None or _sha256_bytes(cftc_count_bytes) != manifest.get(
        "cftc_count_proof_sha256"
    ):
        raise CFTCExperimentError("Development CFTC count proof differs from the manifest")
    current_hashes = _source_hashes(repo_root)
    if current_hashes != manifest.get("source_hashes"):
        raise CFTCExperimentError("Frozen source hashes differ from development")
    if not _git_commit_is_ancestor(
        repo_root,
        str(manifest.get("git_commit") or ""),
        captured_head,
    ):
        raise CFTCExperimentError("Development Git commit is not an ancestor of confirmation")
    price_frame = _assert_stage_frame_bounds(
        pd.read_csv(io.BytesIO(price_bytes)),
        start=DEVELOPMENT_PRICE_START,
        end=DEVELOPMENT_END,
        stage="development_replay",
    )
    metadata_payload = _snapshot_json(snapshot, "cftc_retrieval_metadata.json")
    if not isinstance(metadata_payload, dict):
        raise CFTCExperimentError("Development CFTC metadata must be a JSON object")
    metadata_payload["contract_codes"] = tuple(metadata_payload["contract_codes"])
    download = COTDownload(
        raw_csv=cftc_bytes,
        count_proof_csv=cftc_count_bytes,
        metadata=COTRetrievalMetadata(**metadata_payload),
    )
    if _sha256_json(download.metadata.as_dict()) != manifest.get(
        "cftc_retrieval_metadata_sha256"
    ):
        raise CFTCExperimentError("Development CFTC metadata differs from the manifest")
    cleaned, coverage = _parse_bounded_download(
        download,
        expected_start=DEVELOPMENT_INPUT_START,
        expected_end=DEVELOPMENT_END,
    )
    policy_records = to_policy_records(cleaned.records)
    replayed_results = []
    replayed_ledger_sets: dict[str, dict[str, pd.DataFrame]] = {}
    for variant in CFTC_COT_VARIANTS:
        replayed, replayed_ledgers = evaluate_variant(
            price_frame,
            policy_records,
            variant_id=variant.variant_id,
            stage="development",
        )
        replayed_results.append(replayed)
        replayed_ledger_sets[variant.variant_id] = replayed_ledgers
    if _sha256_json(replayed_results) != manifest.get("evaluation_results_sha256"):
        raise CFTCExperimentError(
            "Deterministic replay from sealed development inputs does not reproduce selection"
        )
    if replayed_results != results:
        raise CFTCExperimentError("Development report differs from deterministic replay")

    expected_artifact_files = {
        ".gitattributes",
        "development_prices_through_2018.csv",
        "development_cftc_raw_through_2018.csv",
        "development_cftc_official_count_proof_through_2018.csv",
        "cftc_retrieval_metadata.json",
        "cftc_exclusions.json",
        "selection_manifest.json",
        "report.json",
        "checksums.json",
    }
    for variant_id, ledgers in replayed_ledger_sets.items():
        expected_artifact_files.update(
            f"{variant_id}_{name}.csv" for name in ledgers
        )
    if set(snapshot) != expected_artifact_files:
        raise CFTCExperimentError(
            "Committed development directory does not match the exact artifact contract"
        )
    if snapshot.get(".gitattributes") != ARTIFACT_GIT_ATTRIBUTES:
        raise CFTCExperimentError("Development artifact byte-preservation rule is invalid")
    expected_embedded_hashes = expected_artifact_files - {"report.json", "checksums.json"}
    if set(artifact_hashes) != expected_embedded_hashes:
        raise CFTCExperimentError(
            "Development embedded artifact hashes do not cover the exact expected payloads"
        )
    expected_exclusions = json.loads(
        json.dumps(
            [asdict(item) for item in cleaned.exclusions],
            sort_keys=True,
            default=_json_default,
        )
    )
    if _snapshot_json(snapshot, "cftc_exclusions.json") != expected_exclusions:
        raise CFTCExperimentError(
            "Development exclusion artifact differs from deterministic reconstruction"
        )
    expected_metadata = json.loads(
        json.dumps(download.metadata.as_dict(), sort_keys=True, default=_json_default)
    )
    if _snapshot_json(snapshot, "cftc_retrieval_metadata.json") != expected_metadata:
        raise CFTCExperimentError(
            "Development metadata artifact differs from validated retrieval metadata"
        )
    for variant_id, ledgers in replayed_ledger_sets.items():
        for name, frame in ledgers.items():
            artifact_name = f"{variant_id}_{name}.csv"
            if snapshot.get(artifact_name) != _ledger_csv_bytes(frame):
                raise CFTCExperimentError(
                    f"Development ledger differs from deterministic replay: {artifact_name}"
                )
    return report, cleaned, coverage, price_frame.tail(1).copy()



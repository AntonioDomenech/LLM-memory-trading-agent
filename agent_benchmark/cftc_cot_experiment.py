class CFTCExperimentError(RuntimeError):
    """Raised when a phase attempts to violate its sealed evidence contract."""


def _json_default(value: Any) -> Any:
    if isinstance(value, (date, datetime, pd.Timestamp)):
        return value.isoformat()
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        return float(value)
    raise TypeError(f"Cannot serialize {type(value)!r}")


def _canonical_json(value: Any) -> str:
    return json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        default=_json_default,
        allow_nan=False,
    )


def _sha256_bytes(payload: bytes) -> str:
    return f"sha256:{hashlib.sha256(payload).hexdigest()}"


def _sha256_hex_bytes(payload: bytes) -> str:
    """Return the bare digest format used by artifact checksum manifests."""

    return hashlib.sha256(payload).hexdigest()


def _sha256_json(value: Any) -> str:
    return _sha256_bytes(_canonical_json(value).encode("utf-8"))


def _frame_csv_bytes(frame: pd.DataFrame) -> bytes:
    return frame.to_csv(
        index=False,
        date_format="%Y-%m-%d",
        float_format="%.17g",
        lineterminator="\n",
    ).encode("utf-8")


def _write_bytes(path: Path, payload: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
    temporary.write_bytes(payload)
    temporary.replace(path)


def _initialize_byte_exact_artifact_directory(run_dir: Path) -> None:
    """Prevent Git line-ending conversion from changing sealed evidence bytes."""

    run_dir.mkdir(parents=True, exist_ok=False)
    _write_bytes(run_dir / ".gitattributes", ARTIFACT_GIT_ATTRIBUTES)


def _assert_stage_frame_bounds(
    frame: pd.DataFrame,
    *,
    start: str,
    end: str,
    stage: str,
) -> pd.DataFrame:
    data = canonical_context_frame(frame)
    lower = pd.Timestamp(start)
    upper = pd.Timestamp(end)
    if data.index.min() < lower or data.index.max() > upper:
        raise CFTCExperimentError(
            f"{stage} price payload contains a row outside its physical "
            f"{start}..{end} boundary"
        )
    if data.index.min() > lower + pd.Timedelta(days=7):
        raise CFTCExperimentError(f"{stage} price payload starts materially after its request")
    if data.index.max() < upper - pd.Timedelta(days=7):
        raise CFTCExperimentError(f"{stage} price payload does not cover its requested end")
    audit_price_response_coverage(data, start=start, end=end, stage=stage)
    return data


def _nth_weekday_of_month(
    year: int,
    month: int,
    *,
    weekday: int,
    occurrence: int,
) -> pd.Timestamp:
    first = pd.Timestamp(year=year, month=month, day=1)
    offset = (weekday - first.weekday()) % 7 + 7 * (occurrence - 1)
    return first + pd.Timedelta(days=offset)


def _last_weekday_of_month(year: int, month: int, *, weekday: int) -> pd.Timestamp:
    first_next_month = pd.Timestamp(year=year, month=month, day=1) + pd.offsets.MonthBegin()
    last = first_next_month - pd.Timedelta(days=1)
    return last - pd.Timedelta(days=(last.weekday() - weekday) % 7)


def _gregorian_easter_sunday(year: int) -> pd.Timestamp:
    """Return Gregorian Easter using the deterministic Meeus/Jones/Butcher rule."""

    a = year % 19
    b, c = divmod(year, 100)
    d, e = divmod(b, 4)
    f = (b + 8) // 25
    g = (b - f + 1) // 3
    h = (19 * a + b - d - g + 15) % 30
    i, k = divmod(c, 4)
    ell = (32 + 2 * e + 2 * i - h - k) % 7
    m = (a + 11 * h + 22 * ell) // 451
    month = (h + ell - 7 * m + 114) // 31
    day = (h + ell - 7 * m + 114) % 31 + 1
    return pd.Timestamp(year=year, month=month, day=day)


def _nearest_weekday_observance(value: pd.Timestamp) -> pd.Timestamp:
    if value.weekday() == 5:
        return value - pd.Timedelta(days=1)
    if value.weekday() == 6:
        return value + pd.Timedelta(days=1)
    return value


def _nyse_full_day_holidays(year: int) -> set[pd.Timestamp]:
    """Return the full-day NYSE closures used by the sealed price phases."""

    new_year = pd.Timestamp(year=year, month=1, day=1)
    # Unlike the other fixed-date holidays, a Saturday New Year's Day does
    # not close the preceding Friday.  A Sunday holiday closes Monday.
    observed_new_year = (
        new_year + pd.Timedelta(days=1) if new_year.weekday() == 6 else new_year
    )
    holidays = {
        observed_new_year,
        _nth_weekday_of_month(year, 1, weekday=0, occurrence=3),  # MLK Day
        _nth_weekday_of_month(year, 2, weekday=0, occurrence=3),  # Presidents Day
        _gregorian_easter_sunday(year) - pd.Timedelta(days=2),  # Good Friday
        _last_weekday_of_month(year, 5, weekday=0),  # Memorial Day
        _nearest_weekday_observance(pd.Timestamp(year=year, month=7, day=4)),
        _nth_weekday_of_month(year, 9, weekday=0, occurrence=1),  # Labor Day
        _nth_weekday_of_month(year, 11, weekday=3, occurrence=4),  # Thanksgiving
        _nearest_weekday_observance(pd.Timestamp(year=year, month=12, day=25)),
    }
    if year >= 2022:
        holidays.add(
            _nearest_weekday_observance(pd.Timestamp(year=year, month=6, day=19))
        )
    holidays.update(value for value in PRE_2024_NYSE_SPECIAL_CLOSURES if value.year == year)
    return holidays


def expected_pre_2024_nyse_sessions(*, start: str, end: str) -> pd.DatetimeIndex:
    """Build the exact expected session sequence for a sealed price request."""

    lower = pd.Timestamp(start).normalize()
    upper = pd.Timestamp(end).normalize()
    if lower > upper:
        raise CFTCExperimentError("Price coverage range starts after it ends")
    if lower < pd.Timestamp(DEVELOPMENT_PRICE_START) or upper > pd.Timestamp(CONFIRMATION_END):
        raise CFTCExperimentError(
            "Exact price-session calendar supports only sealed 1999-12-31 through 2023 requests"
        )
    holidays: set[pd.Timestamp] = set()
    for year in range(lower.year, upper.year + 1):
        holidays.update(_nyse_full_day_holidays(year))
    weekdays = pd.date_range(lower, upper, freq="B")
    return pd.DatetimeIndex(value for value in weekdays if value not in holidays)


def _session_sequence_sha256(dates: pd.DatetimeIndex) -> str:
    payload = "".join(f"{value.date().isoformat()}\n" for value in dates).encode("ascii")
    return _sha256_bytes(payload)


def audit_price_response_coverage(
    frame: pd.DataFrame,
    *,
    start: str,
    end: str,
    stage: str,
) -> dict[str, Any]:
    data = canonical_context_frame(frame)
    dates = data.index
    expected = expected_pre_2024_nyse_sessions(start=start, end=end)
    missing = expected.difference(dates)
    unexpected = dates.difference(expected)
    gaps = np.diff(dates.values).astype("timedelta64[D]").astype(int)
    maximum_gap = int(gaps.max()) if len(gaps) else 0
    approximate_weekdays = len(pd.bdate_range(start, end))
    coverage_ratio = len(dates) / max(1, approximate_weekdays)
    exact_coverage_ratio = (len(expected) - len(missing)) / max(1, len(expected))
    passed = bool(dates.equals(expected))
    audit = {
        "stage": stage,
        "session_calendar_id": PRICE_SESSION_CALENDAR_ID,
        "first_session": dates.min().date().isoformat(),
        "last_session": dates.max().date().isoformat(),
        "sessions": int(len(dates)),
        "expected_sessions": int(len(expected)),
        "exact_expected_session_coverage_ratio": exact_coverage_ratio,
        "missing_sessions": int(len(missing)),
        "unexpected_sessions": int(len(unexpected)),
        "missing_session_examples": [value.date().isoformat() for value in missing[:10]],
        "unexpected_session_examples": [
            value.date().isoformat() for value in unexpected[:10]
        ],
        "expected_date_sequence_sha256": _session_sequence_sha256(expected),
        "observed_date_sequence_sha256": _session_sequence_sha256(dates),
        "approximate_weekday_sessions": int(approximate_weekdays),
        "approximate_weekday_coverage_ratio": coverage_ratio,
        "maximum_internal_calendar_gap_days": maximum_gap,
        "passed": passed,
    }
    if not passed:
        raise CFTCExperimentError(
            f"{stage} price payload has incomplete internal coverage "
            f"({len(missing)} missing, {len(unexpected)} unexpected sessions)"
        )
    return audit



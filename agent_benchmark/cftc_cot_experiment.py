def _verify_saved_phase_payloads(
    run_dir: Path,
    *,
    price_filename: str,
    price_payload: bytes,
    cftc_filename: str,
    cftc_count_filename: str,
    cftc_download: COTDownload,
    exclusions: Sequence[Mapping[str, Any]],
    manifest_filename: str,
    manifest: Mapping[str, Any],
    ledger_sets: Mapping[str, Mapping[str, pd.DataFrame]],
) -> list[str]:
    errors: list[str] = []
    if (run_dir / price_filename).read_bytes() != price_payload:
        errors.append("saved_price_payload_mismatch")
    if (run_dir / cftc_filename).read_bytes() != cftc_download.raw_csv:
        errors.append("saved_cftc_payload_mismatch")
    if (run_dir / cftc_count_filename).read_bytes() != cftc_download.count_proof_csv:
        errors.append("saved_cftc_count_proof_mismatch")
    saved_metadata = json.loads(
        (run_dir / "cftc_retrieval_metadata.json").read_text(encoding="utf-8")
    )
    if saved_metadata != cftc_download.metadata.as_dict():
        # JSON converts the contract-code tuple to a list.
        expected_metadata = json.loads(
            json.dumps(cftc_download.metadata.as_dict(), sort_keys=True)
        )
        if saved_metadata != expected_metadata:
            errors.append("saved_cftc_metadata_mismatch")
    saved_exclusions = json.loads(
        (run_dir / "cftc_exclusions.json").read_text(encoding="utf-8")
    )
    expected_exclusions = json.loads(
        json.dumps(
            list(exclusions),
            sort_keys=True,
            default=_json_default,
        )
    )
    if saved_exclusions != expected_exclusions:
        errors.append("saved_cftc_exclusions_mismatch")
    saved_manifest = json.loads(
        (run_dir / manifest_filename).read_text(encoding="utf-8")
    )
    if saved_manifest != manifest:
        errors.append("saved_phase_manifest_mismatch")
    for variant_id, ledgers in ledger_sets.items():
        for name, frame in ledgers.items():
            path = run_dir / f"{variant_id}_{name}.csv"
            if not path.is_file() or path.read_bytes() != _ledger_csv_bytes(frame):
                errors.append(f"saved_ledger_mismatch:{variant_id}:{name}")
    return errors


def _write_checksums(run_dir: Path) -> dict[str, str]:
    hashes = {
        str(path.relative_to(run_dir)).replace("\\", "/"): file_sha256(path)
        for path in sorted(run_dir.iterdir())
        if path.is_file() and path.name != "checksums.json"
    }
    _atomic_write_text(
        run_dir / "checksums.json",
        json.dumps(hashes, indent=2, sort_keys=True) + "\n",
    )
    return hashes


def _verify_complete_artifact_directory(
    run_dir: Path,
    *,
    expected_files: set[str],
) -> dict[str, bytes]:
    """Read a finished run once and verify its exact checksum-covered file set."""

    snapshot = {
        path.name: path.read_bytes()
        for path in run_dir.iterdir()
        if path.is_file()
    }
    _verify_artifact_snapshot(snapshot, expected_files=expected_files)
    return snapshot


def _verify_artifact_snapshot(
    snapshot: Mapping[str, bytes],
    *,
    expected_files: set[str],
) -> None:
    """Verify an artifact snapshot loaded from either a directory or Git blobs."""

    if set(snapshot) != expected_files:
        raise CFTCExperimentError("Finished run directory violates the exact artifact contract")
    try:
        checksums = json.loads(snapshot["checksums.json"].decode("utf-8", errors="strict"))
    except (KeyError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise CFTCExperimentError("Finished run has an invalid checksum manifest") from exc
    expected_checksum_names = expected_files - {"checksums.json"}
    if not isinstance(checksums, dict) or set(checksums) != expected_checksum_names:
        raise CFTCExperimentError("Finished checksum manifest does not cover the exact files")
    for name, expected_hash in checksums.items():
        if _sha256_hex_bytes(snapshot[name]) != expected_hash:
            raise CFTCExperimentError(f"Finished artifact checksum mismatch: {name}")


def _artifact_hashes_for_report(run_dir: Path) -> dict[str, str]:
    """Hash immutable payloads without creating a report/checksum hash cycle."""

    return {
        str(path.relative_to(run_dir)).replace("\\", "/"): file_sha256(path)
        for path in sorted(run_dir.iterdir())
        if path.is_file() and path.name not in {"report.json", "checksums.json"}
    }


def _git_commit_is_ancestor(repo_root: Path, older: str, newer: str) -> bool:
    if not older or not newer:
        return False
    completed = subprocess.run(
        ["git", "merge-base", "--is-ancestor", older, newer],
        cwd=repo_root,
        capture_output=True,
        text=True,
        check=False,
    )
    return completed.returncode == 0


def _confirmation_registry_path(repo_root: Path) -> Path:
    completed = subprocess.run(
        ["git", "rev-parse", "--git-common-dir"],
        cwd=repo_root,
        check=True,
        capture_output=True,
        text=True,
    )
    common = Path(completed.stdout.strip())
    if not common.is_absolute():
        common = (repo_root / common).resolve()
    return (
        common
        / "codex-evidence"
        / "aapl-cftc-cot-sentiment-v1"
        / "confirmation_access_2019_2023.json"
    )


def reserve_confirmation_access(
    registry_path: Path,
    *,
    development_run_id: str,
    development_manifest_sha256: str,
    selected_variant_id: str,
) -> dict[str, Any]:
    """Atomically consume the one permitted 2019-2023 confirmation reveal."""

    registry_path.parent.mkdir(parents=True, exist_ok=True)
    completion_path = _confirmation_completion_path(registry_path)
    if completion_path.exists():
        raise CFTCExperimentError(
            "The confirmation completion record already exists; the 2019-2023 "
            "block was previously accessed"
        )
    reservation = {
        "access_id": f"cftc-confirmation-{uuid.uuid4().hex}",
        "reserved_at_utc": datetime.now(timezone.utc).isoformat(),
        "status": "reserved_before_data_access",
        "development_run_id": development_run_id,
        "development_manifest_sha256": development_manifest_sha256,
        "selected_variant_id": selected_variant_id,
        "confirmation_window": {
            "start": CONFIRMATION_START,
            "end": CONFIRMATION_END,
        },
    }
    encoded = (json.dumps(reservation, indent=2, sort_keys=True) + "\n").encode("utf-8")
    _exclusive_write(registry_path, encoded, label="confirmation reservation")
    if completion_path.exists():
        raise CFTCExperimentError(
            "A prior confirmation completion record appeared while reserving access; "
            "the new reservation remains as a fail-closed sentinel"
        )
    return reservation


def _exclusive_write(path: Path, payload: bytes, *, label: str) -> None:
    """Create one immutable evidence record without replacing an existing file."""

    try:
        descriptor = os.open(
            path,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0),
        )
    except FileExistsError as exc:
        raise CFTCExperimentError(
            f"The {label} already exists; do not overwrite one-shot evidence"
        ) from exc
    try:
        remaining = memoryview(payload)
        while remaining:
            written = os.write(descriptor, remaining)
            if written <= 0:
                raise CFTCExperimentError(f"Could not finish writing {label}")
            remaining = remaining[written:]
        os.fsync(descriptor)
    finally:
        os.close(descriptor)



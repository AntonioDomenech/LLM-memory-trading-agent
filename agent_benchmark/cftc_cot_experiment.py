def _finish_confirmation_access(
    registry_path: Path,
    reservation: Mapping[str, Any],
    *,
    run_id: str,
    confirmation_pass: bool,
    confirmation_manifest_sha256: str = "",
    artifact_checksums_sha256: str = "",
) -> dict[str, Any]:
    if not confirmation_manifest_sha256 or not artifact_checksums_sha256:
        raise CFTCExperimentError(
            "Confirmation completion requires the sealed manifest and artifact checksums"
        )
    expected_reservation = (
        json.dumps(dict(reservation), indent=2, sort_keys=True) + "\n"
    ).encode("utf-8")
    try:
        observed_reservation = registry_path.read_bytes()
    except OSError as exc:
        raise CFTCExperimentError("Confirmation reservation disappeared before completion") from exc
    if observed_reservation != expected_reservation:
        raise CFTCExperimentError(
            "Confirmation reservation changed before completion; refusing to overwrite evidence"
        )
    completion_path = _confirmation_completion_path(registry_path)
    finished = {
        **dict(reservation),
        "status": "completed",
        "completed_at_utc": datetime.now(timezone.utc).isoformat(),
        "confirmation_run_id": run_id,
        "confirmation_pass": bool(confirmation_pass),
        "confirmation_manifest_sha256": confirmation_manifest_sha256,
        "artifact_checksums_sha256": artifact_checksums_sha256,
        "reservation_sha256": _sha256_bytes(expected_reservation),
        "immutable_reservation_record": registry_path.name,
        "completion_record": completion_path.name,
    }
    encoded_completion = (
        json.dumps(finished, indent=2, sort_keys=True) + "\n"
    ).encode("utf-8")
    _exclusive_write(
        completion_path,
        encoded_completion,
        label="confirmation completion record",
    )
    if registry_path.read_bytes() != expected_reservation:
        raise CFTCExperimentError(
            "Confirmation reservation changed during completion; immutable records preserved"
        )
    return finished



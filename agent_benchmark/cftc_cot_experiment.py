"""Sealed pre-2024 experiment for the four CFTC COT sentiment variants.

The development phase is physically bounded at 2018-12-31.  It may compare
the four predeclared policies and select at most one.  The confirmation phase
is physically bounded at 2023-12-31 and may evaluate only that frozen winner.
No function in this module accepts a post-2023 date.

Both phases use the existing same-ledger, next-adjusted-open AAPL simulator.
Targets are binary (100% AAPL or 100% cash), cash cannot become negative, and
the simulator's no-leverage proof is part of every gate and artifact.
"""

